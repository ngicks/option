func main() {
	arities := make([]int, maxN-1)
	for n := 2; n <= maxN; n++ {
		arities[n-2] = n
	}
	for name, tmpl := range map[string]string{
		"tuple.generated.go":         tupleTmpl,
		"zip.generated.go":           zipTmpl,
		"zipopt.generated.go":        zipOptTmpl,
		"unzip.generated.go":         unzipTmpl,
		"unzipopt.generated.go":      unzipOptTmpl,
		"tuple.generated_test.go":    tupleTestTmpl,
		"zip.generated_test.go":      zipTestTmpl,
		"zipopt.generated_test.go":   zipOptTestTmpl,
		"unzip.generated_test.go":    unzipTestTmpl,
		"unzipopt.generated_test.go": unzipOptTestTmpl,
	} {
		b := &strings.Builder{}
		b.WriteString(header)
		if err := template.Must(template.New(name).Funcs(funcs).Parse(tmpl)).Execute(b, arities); err != nil {
			panic(fmt.Errorf("execute %s: %w", name, err))
		}
		formatted, err := format.Source([]byte(b.String()))
		if err != nil {
			panic(fmt.Errorf("format %s: %w", name, err))
		}
		if err := os.WriteFile(name, formatted, 0o644); err != nil {
			panic(err)
		}
	}
}
