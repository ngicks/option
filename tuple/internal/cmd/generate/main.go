// slice length used in tests for the j-th slice: cycles 1, 2, 3.
func testLen(j int) int { return (j-1)%3 + 1 }

// test value for j-th slice, 0-based index i.
func testVal(j, i int) int { return j*100 + i + 1 }

var funcs = template.FuncMap{
	"seq": func(n int) []int {
		s := make([]int, n)
		for i := range s {
			s[i] = i + 1
		}
		return s
	},
	"seq0": func(n int) []int {
		s := make([]int, n)
		for i := range s {
			s[i] = i
		}
		return s
	},
	"testLen": testLen,
	"testVal": testVal,
	"outLen": func(n int) int {
		l := 0
		for j := 1; j <= n; j++ {
			l = max(l, testLen(j))
		}
		return l
	},
}

